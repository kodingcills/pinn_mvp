"""Render docs/eval_program/M4_REPORT.md from committed M4 campaign artifacts.

    .venv/bin/python scripts/m4_render_report.py [--phase campaign] [--out PATH] [--check]

Every number comes from results/m4/<phase>/official_metrics.json, raw_rows.jsonl
and replay_index.jsonl; the rules text comes from the pre-registration. Output
is a pure function of those files, so a second render is byte-identical and
`--check` fails when the committed report drifts from the artifacts.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PREREG = REPO / "docs" / "eval_program" / "designs" / "M4_preregistration.md"
OUT = REPO / "docs" / "eval_program" / "M4_REPORT.md"
GUARDED = ("haplous_mediated", "g1_incumbent")
CONTEXT = {"bare_behavior": "direct execution (HES baseline), context",
           "competent_supervisor": "historical HES supervisor, context only, not an incumbent"}


def _load(phase: str) -> dict:
    root = REPO / "results" / "m4" / phase
    files = {k: root / f for k, f in (("official", "official_metrics.json"), ("rows", "raw_rows.jsonl"),
                                       ("replays", "replay_index.jsonl"))}
    jsonl = lambda p: [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]  # noqa: E731
    return {"root": root, "official": json.loads(files["official"].read_text(encoding="utf-8")),
            "rows": jsonl(files["rows"]), "replays": jsonl(files["replays"]),
            "digests": {f.relative_to(REPO).as_posix(): hashlib.sha256(f.read_bytes()).hexdigest() for f in files.values()}}


def _rules_text() -> str:
    text = PREREG.read_text(encoding="utf-8")
    start = text.index("1. lo > 0:")
    return text[start:text.index("\n\nExactly one rule", start)]


def _f(x, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def _prop(p: dict) -> str:
    if p is None or p.get("value") is None:
        return f"NOT_AVAILABLE (n={p.get('n', 0) if p else 0})"
    k = round(p["value"] * p["n"])
    return f"{p['value']:.3f} ({k}/{p['n']}) [{p['ci_low']:.3f}, {p['ci_high']:.3f}]"


def _delta(d: dict) -> str:
    return f"{d['delta']:+.4f} [{d['ci_low']:+.4f}, {d['ci_high']:+.4f}] (n={d['n_pairs']} pairs)"


def _stratum(row: dict) -> str:
    tags = [str(t) for t in row.get("tags") or ()]
    return next((t for t in tags if t.startswith("stratum:")), next((t for t in tags if t.startswith("task_")), "none"))


def _outcome(row: dict) -> str:
    why = row.get("reason") or ",".join(row.get("refusal_codes") or ()) or "-"
    return f"{row['reported_disposition']} / viol {row['n_hard_violations']} / {why}"


def render(phase: str) -> str:
    data = _load(phase)
    off = data["official"]
    pops = off["populations"]
    pop_ids = {}
    rows: dict[tuple[str, str, str], dict] = {}
    for r in data["rows"]:
        rows[(r["metadata"]["population_id"], r["scenario_id"], r["arm"])] = r
    for pid, _, _ in rows:
        pop_ids.setdefault(pid.split("@")[0].removeprefix("m4_"), pid)
    replays = {(e["population"], e["scenario_id"], e["arm"]): e for e in data["replays"]}
    arms = list(next(iter(pops.values()))["arms"])
    L: list[str] = []
    w = L.append

    w("# M4 report: Haplous vs a competent incumbent (G1) vs direct execution")
    w("")
    w(f"Generated by `scripts/m4_render_report.py --phase {phase}` from committed artifacts; do not hand-edit.")
    w(f"Phase `{phase}`, scoring epoch `{off['scoring_epoch']}`, config_sha256 `{off['config_sha256']}`.")
    w("Protocol: `docs/eval_program/designs/M4_preregistration.md` (r2, frozen). Inputs (SHA-256):")
    w("")
    for path, digest in data["digests"].items():
        w(f"- `{path}` `{digest}`")
    w("")
    w("SCRIPTED-POLICY SIMULATION on MuJoCo. Not VLA performance, not hardware. See \"What this does NOT show\".")
    w("")

    w("## 1. Headline verdicts (confirmatory)")
    w("")
    w("Bounded success, `haplous_mediated` minus `g1_incumbent`, scenario-paired percentile bootstrap 95%"
      " (10 000 resamples, seed 20261113). Decision rules, applied in order, first match wins (pre-registration"
      " section 6, verbatim):")
    w("")
    w(_rules_text())
    w("")
    w("| Id | Population | Delta [95% CI] | Verdict | Rescued | Harmed |")
    w("|---|---|---|---|---|---|")
    for pop, m in sorted(pops.items(), key=lambda kv: next(iter(kv[1]["confirmatory"]), "")):
        for cid, c in m["confirmatory"].items():
            verdict = c["decision"]
            if verdict.startswith("Haplous better") and c["n_harmed"]:
                verdict += "; advantage with regressions"
            w(f"| {cid} | {pop} ({pop_ids.get(pop, pop)}) | {_delta(c['delta'])} | **{verdict}** "
              f"| {c['n_rescued']} | {c['n_harmed']} |")
    w("")
    w("A G1 win or a tie carries the same weight as a Haplous win. Each verdict answers its own question;"
      " no family-wise claim is made.")
    w("")

    w("## 2. Estimands per population and arm")
    w("")
    w("Resampling unit: the scenario (one shared machine realization, one episode per arm). Proportions:"
      " Wilson 95% (value (numerator/denominator) [lo, hi]). All rows in this section are EXPLORATORY except"
      " bounded success of the two guarded arms, which feeds C1/C2 through the paired delta. Arms marked"
      " context are not incumbents.")
    defs = [
        ("task_success", "task success", "all scheduled"),
        ("bounded_success", "bounded success", "all scheduled"),
        ("coverage", "acceptance coverage (not REFUSED)", "all scheduled"),
        ("violation_given_acceptance", "violation given acceptance", "accepted episodes"),
        ("false_refusal_rate", "false refusal", "scheduled scenarios demonstrated attainable"),
        ("preservation_vs_direct", "non-interference: preservation vs bare_behavior",
         "scenarios where bare_behavior reached bounded success"),
        ("unnecessary_intervention_vs_direct", "unnecessary intervention vs bare_behavior",
         "scenarios where bare_behavior reached bounded success"),
        ("recovery_bounded_success", "recovery: bounded success", "scheduled scenarios tagged recovery_authorized"),
    ]
    for pop, m in pops.items():
        w("")
        w(f"### {pop} ({pop_ids.get(pop, pop)}), {m['n_scenarios']} scheduled scenarios")
        w("")
        w(f"Attainability: {', '.join(f'{k} {v}' for k, v in m['attainability_counts'].items())}.")
        w("")
        w("| Estimand (denominator) | " + " | ".join(a + (" (context)" if a in CONTEXT else "") for a in arms) + " |")
        w("|---|" + "---|" * len(arms))
        for key, label, denom in defs:
            w(f"| {label} ({denom}) | " + " | ".join(
                "-" if m["arms"][a][key] is None else _prop(m["arms"][a][key]) for a in arms) + " |")
        w("| refusals with attainability UNKNOWN (count) | "
          + " | ".join(str(m["arms"][a]["refusals_attainability_unknown"]) for a in arms) + " |")
    w("")

    w("## 3. Paired comparisons (bounded success)")
    w("")
    w("Rescued: candidate bounded, reference not. Harmed: reference bounded, candidate not."
      " Only the two `haplous_mediated_vs_g1_incumbent` rows are confirmatory (C1 stress, C2 control).")
    w("")
    w("| Population | Comparison | Status | Delta [95% CI] | Rescued | Harmed | Both | Neither |")
    w("|---|---|---|---|---|---|---|---|")
    for pop, m in pops.items():
        for name, p in m["paired"].items():
            status = "CONFIRMATORY" if name == "haplous_mediated_vs_g1_incumbent" else "exploratory"
            if "competent_supervisor" in name:
                status += " (historical reference)"
            w(f"| {pop} | `{name}` | {status} | {_delta(p['delta_bounded_success'])} | {len(p['rescued'])} "
              f"| {len(p['harmed'])} | {p['both']} | {p['neither']} |")
    w("")

    w("## 4. Every rescued and harmed scenario, with replay")
    w("")
    w("Outcome cells: disposition / hard violations / reason or refusal codes, from `raw_rows.jsonl`."
      " Replay opens the M0-sealed recording; add `--rrd replays/<run_id>.rrd` for the 3D Rerun view."
      " Bulk recordings live in the gitignored store; when absent, `scripts/m4_campaign.py validate --phase "
      f"{phase}` regenerates them and checks their digests against `replay_index.jsonl`."
      " Rows marked EXEMPLAR are also sealed in the committed registry. Recording selection and its cap of"
      " 25 pairs per population follow pre-registration section 9; pairs beyond the cap are marked"
      " \"not recorded\".")
    w("")
    n_ex = sum(1 for e in data["replays"] if e["exemplar_registry"])
    w(f"Recordings indexed: {len(data['replays'])}; committed exemplar recordings: {n_ex}. Exemplars are drawn"
      " only from the Haplous-vs-G1 rescued and harmed classes (section 9), so an empty class commits none.")
    for cand, ref in (("haplous_mediated", "g1_incumbent"), ("haplous_mediated", "bare_behavior")):
        name = f"{cand}_vs_{ref}"
        status = "CONFIRMATORY comparison" if ref == "g1_incumbent" else "exploratory comparison"
        for pop, m in pops.items():
            pid = pop_ids.get(pop, pop)
            p = m["paired"][name]
            for kind in ("rescued", "harmed"):
                w("")
                w(f"### {pop}: {kind}, `{name}` ({status}): {len(p[kind])}")
                w("")
                if not p[kind]:
                    w("None.")
                    continue
                w(f"| Scenario | Stratum | {cand} | {ref} | Replay ({cand} / {ref}) |")
                w("|---|---|---|---|---|")
                for sid in p[kind]:
                    c, r = rows[(pid, sid, cand)], rows[(pid, sid, ref)]
                    cmds = []
                    for arm in (cand, ref):
                        e = replays.get((pop, sid, arm))
                        if e is None:
                            cmds.append("not recorded (cap of 25 pairs)")
                            continue
                        cmd = e["replay_command"]
                        if e["exemplar_registry"]:
                            cmd = cmd.replace(e["registry"], e["exemplar_registry"]) + "` EXEMPLAR"
                        else:
                            cmd += "`"
                        cmds.append("`" + cmd)
                    w(f"| `{sid}` | {_stratum(c)} | {_outcome(c)} | {_outcome(r)} | {' / '.join(cmds)} |")
    w("")
    w("Remaining exploratory comparisons, scenario ids (not recorded by design):")
    w("")
    for pop, m in pops.items():
        for name, p in m["paired"].items():
            if name in ("haplous_mediated_vs_g1_incumbent", "haplous_mediated_vs_bare_behavior"):
                continue
            for kind in ("rescued", "harmed"):
                ids = ", ".join(f"`{s}`" for s in p[kind]) or "none"
                w(f"- {pop} `{name}` {kind} ({len(p[kind])}): {ids}")
    w("")

    w("## 5. What drives the confirmatory discordance")
    w("")
    w("Discordant Haplous-vs-G1 pairs counted by stratum, and the outcome pair (Haplous disposition and"
      " reason, G1 disposition and reason) behind them. Computed from `raw_rows.jsonl`.")
    for pop, m in pops.items():
        pid = pop_ids.get(pop, pop)
        p = m["paired"]["haplous_mediated_vs_g1_incumbent"]
        w("")
        w(f"### {pop}")
        w("")
        disc = [(k, s) for k in ("rescued", "harmed") for s in p[k]]
        if not disc:
            n = m["n_scenarios"]
            w(f"No discordant pairs in {n} scenarios: the two guarded arms reached the same bounded-success"
              f" outcome on every scenario, so every bootstrap resample has delta 0 and the percentile interval"
              f" is degenerate at [0, 0]. As a non-pre-registered aid (exploratory), the rule-of-three 95%"
              f" upper bound on the per-scenario discordance rate is 3/{n} = {3 / n:.4f}.")
            w("")
            same = sum(1 for (q, s, a), r in rows.items() if q == pid and a == "haplous_mediated"
                       and r["reported_disposition"] == rows[(pid, s, "g1_incumbent")]["reported_disposition"])
            w(f"Reported dispositions also agree on {same}/{n} scenarios. Guarded-arm outcomes by stratum"
              " (Haplous reason ; G1 reason, count):")
            w("")
            w("| Stratum | Haplous outcome | G1 outcome | Count |")
            w("|---|---|---|---|")
            agg = Counter((_stratum(r), r["reported_disposition"] + " " + (r["reason"] or "-"),
                           rows[(pid, s, "g1_incumbent")]["reported_disposition"] + " "
                           + (rows[(pid, s, "g1_incumbent")]["reason"] or "-"))
                          for (q, s, a), r in rows.items() if q == pid and a == "haplous_mediated")
            for (st, h, g), k in sorted(agg.items()):
                w(f"| {st} | {h} | {g} | {k} |")
            diff = sorted(s for (q, s, a), r in rows.items() if q == pid and a == "haplous_mediated"
                          and r["reported_disposition"] != rows[(pid, s, "g1_incumbent")]["reported_disposition"])
            if diff:
                w("")
                w("Scenarios where the reported dispositions differ (bounded success still agrees), with peak"
                  " absolute force (N) and violation codes per arm:")
                w("")
                w("| Scenario | haplous_mediated | g1_incumbent | bare_behavior |")
                w("|---|---|---|---|")
                for s in diff:
                    cells = []
                    for arm in ("haplous_mediated", "g1_incumbent", "bare_behavior"):
                        r = rows[(pid, s, arm)]
                        codes = ",".join(sorted({v.get("code", "?") for v in r["hard_violations"]})) or "none"
                        cells.append(f"{r['reported_disposition']} {r['reason'] or '-'}; peak "
                                     f"{_f(r['task_metrics'].get('peak_abs_force_n'), 1)} N; viol {codes}")
                    w(f"| `{s}` | " + " | ".join(cells) + " |")
            continue
        by_stratum = Counter((_stratum(rows[(pid, s, "haplous_mediated")]), k) for k, s in disc)
        w("| Stratum | Rescued | Harmed | Scenarios in stratum |")
        w("|---|---|---|---|")
        for name in sorted({st for st, _ in by_stratum}):
            w(f"| {name} | {by_stratum[(name, 'rescued')]} | {by_stratum[(name, 'harmed')]} "
              f"| {m['strata'].get(name, {}).get('n_scenarios', 'n/a')} |")
        w("")
        pairs = Counter((k, _outcome(rows[(pid, s, "haplous_mediated")]).split(" / ", 1)[0] + " " +
                         (rows[(pid, s, "haplous_mediated")]["reason"] or "-"),
                         rows[(pid, s, "g1_incumbent")]["reported_disposition"] + " " +
                         (rows[(pid, s, "g1_incumbent")]["reason"] or "-")) for k, s in disc)
        w("| Class | Haplous outcome | G1 outcome | Count |")
        w("|---|---|---|---|")
        for (k, h, g), n in sorted(pairs.items()):
            w(f"| {k} | {h} | {g} | {n} |")
    w("")

    w("## 6. Strata and task families (exploratory)")
    w("")
    w("| Population | Stratum | n | " + " | ".join(arms) + " | H vs G1 rescued/harmed |")
    w("|---|---|---|" + "---|" * len(arms) + "---|")
    for pop, m in pops.items():
        for name, s in m["strata"].items():
            hg = s["paired"]["haplous_mediated_vs_g1_incumbent"]
            w(f"| {pop} | {name} | {s['n_scenarios']} | "
              + " | ".join(_prop(s["bounded_success"][a]) for a in arms) + f" | {hg['rescued']}/{hg['harmed']} |")
    w("")

    w("## 7. Time (exploratory)")
    w("")
    w("Total simulated time per accepted task = (simulated seconds of every executed episode + reset_s per"
      " executed episode) / bounded successes. reset_s 1.0 s is an assumption (the substrate models no"
      " reset); 0.0 s is the sensitivity case. Intervention overhead is the median over scenarios where both"
      " the arm and bare_behavior reached bounded success of (arm minus bare_behavior simulated duration);"
      " both episodes execute, so reset_s cancels and the value is the same at 1.0 s and 0.0 s.")
    w("")
    w("| Population | Arm | s per accepted task, reset 1.0 | s per accepted task, reset 0.0 | Executed | Bounded"
      " | Overhead vs direct, median s (n) |")
    w("|---|---|---|---|---|---|---|")
    for pop, m in pops.items():
        for a in arms:
            t = m["arms"][a]["time_per_bounded_success"]
            o = m["arms"][a]["intervention_overhead_vs_direct"]
            label = a + (" (context)" if a in CONTEXT else "")
            w(f"| {pop} | {label} | {_f(t['by_reset_s']['1.0'])} | {_f(t['by_reset_s']['0.0'])} "
              f"| {t['n_executed']} | {t['n_bounded_success']} "
              f"| {'-' if o is None else _f(o['median_sim_s'], 4) + ' (' + str(o['n']) + ')'} |")
    w("")

    w("## 8. Exclusions (decided before execution, section 7)")
    w("")
    w("| Population | Rule | Count | Scenario ids |")
    w("|---|---|---|---|")
    for pop, m in pops.items():
        for rule, x in m["exclusions"].items():
            w(f"| {pop} | `{rule}` | {x['count']} | {', '.join(f'`{s}`' for s in x['scenario_ids']) or '-'} |")
    w("")

    w("## 9. HES hard gates (runtime arm `haplous_mediated`, baseline `bare_behavior`)")
    w("")
    w("Reported as HES computes them, never overridden. A failed gate stays failed.")
    w("")
    w("| Population | Gate | Passed | Observed | Threshold |")
    w("|---|---|---|---|---|")
    for pop, m in pops.items():
        hg = m["hes_hard_gates"]
        for g in hg["gates"]:
            obs = json.dumps(g["observed"], sort_keys=True)
            obs = obs if len(obs) <= 80 else obs[:77] + "..."
            w(f"| {pop} | {g['gate_id']} {g['name']} | {'PASS' if g['passed'] else '**FAIL**'} | `{obs}` "
              f"| {g['threshold']} |")
        w(f"| {pop} | qualified | {'yes' if hg['qualified'] else '**no**'} | | |")
    w("")
    w("Full HES reports: " + ", ".join(f"`results/m4/{phase}/{pop}/HES_REPORT.md`" for pop in pops) + ".")
    w("")

    w("## 10. Context arms")
    w("")
    for a, label in CONTEXT.items():
        w(f"- `{a}`: {label}. Its numbers appear in sections 2, 3, 6 and 7 for context; it is never the"
          " reference of a confirmatory comparison.")
    w("")

    w("## 11. What this does NOT show")
    w("")
    for line in (
        "SCRIPTED-POLICY SIMULATION: every arm drives the same scripted MuJoCo behaviour. Nothing here measures"
        " a VLA or any learned policy.",
        "No OEM or hardware claim. The machine, its faults and its physics are simulated.",
        "Adapter machines (G1 asymmetry 1) are untested: no behaviour authorizes a command-mode substitute,"
        " so G1 and Haplous both refuse there by construction.",
        "G1 is mildly strong: it reads the machine's qualification record (`expected_duration_s`,"
        " `max_initial_offset_m`) for free and has authorized budgeted retry. The disclosed asymmetries"
        " (G1 design section 6) favour G1, which is conservative for Haplous claims.",
        "Slides with translational disturbances and the two named slide scenarios are excluded as mesh"
        " artifacts (16-tile annulus facet taps, KNOWN_ISSUES); slide results cover only undisturbed or"
        " rotationally disturbed slides.",
        "`docs/HES_V0_REPORT.md` is stale on main (digest drift, KNOWN_ISSUES) and is not M4 evidence; epoch"
        " `hes-m4-e2` is not poolable with it or any earlier epoch.",
        "HES intervention-quality metrics need counterfactual forks, not run here (NOT_AVAILABLE).",
        "Agreement between Haplous and G1 is partly by construction: hold budget, recovery episode and"
        " restart from the live pose use the same machine and behaviour hooks (G1 design section 6, item 7)."
        " A tie here is not evidence that either guard set is sufficient, only that they coincide on these"
        " populations.",
        "The stress population probes the regions named by the M4.1 verifier; its rates are not field rates.",
    ):
        w(f"- {line}")
    w("")
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="m4_render_report")
    parser.add_argument("--phase", default="campaign", choices=("dryrun", "campaign"))
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="fail if --out differs from a fresh render")
    args = parser.parse_args(argv)
    text = render(args.phase)
    if args.check:
        same = args.out.is_file() and args.out.read_text(encoding="utf-8") == text
        print(f"{args.out}: {'matches' if same else 'DIFFERS from'} the artifacts")
        return 0 if same else 1
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
